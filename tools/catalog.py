#!/usr/bin/env python3
# Writes the feature indexes: island/widgets/index.js and dashboard/widgets/index.js, one line per
# <id>/meta.js folder (R2 C5, the feature-folder contract). A folder with a meta.js is in the shell;
# nothing else has to be edited to add one. tools/check runs this and fails when an index is stale,
# and <area>/tests/index.test.js checks the same thing on `main`, where this script doesn't ship.
#
#   python3 -I tools/catalog.py [--check]        (VTNC = the shell, default the one around tools/)
import os, re, sys

VTNC = os.path.realpath(os.environ.get("VTNC") or os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
AREAS = [("island/widgets", "Iwidget"), ("dashboard/widgets", "Dwidget")]


def qualifier(wid):
    # "quick" → "Quick", "active-window" → "ActiveWindow"; the qualifier of a `.import`
    return "M" + "".join(p[:1].upper() + p[1:] for p in re.split(r"[-_]", wid))


def ids(area):
    d = os.path.join(VTNC, area)
    return sorted(n for n in os.listdir(d) if os.path.isfile(os.path.join(d, n, "meta.js")))


def index(area, kind):
    out = [".pragma library\n",
           "\n",
           "// GENERATED by tools/catalog.py: one line per %s folder (<id>/meta.js). Do not edit;\n" % kind,
           "// add or remove a folder and run `tools/check` (or tools/catalog.py).\n"]
    names = ids(area)
    out += ['.import "%s/meta.js" as %s\n' % (w, qualifier(w)) for w in names]
    out += ["\n", "var WIDGETS = {\n"]
    out += ["    %s: %s.meta%s\n" % (w, qualifier(w), "," if i < len(names) - 1 else "")
            for i, w in enumerate(names)]
    out += ["};\n"]
    return "".join(out)


stale = []
for area, kind in AREAS:
    # an area whose folders have no meta.js yet (R2 C5 does one area at a time) has no index
    if not ids(area):
        continue
    p = os.path.join(VTNC, area, "index.js")
    new = index(area, kind)
    old = open(p).read() if os.path.exists(p) else None
    if old == new:
        continue
    if "--check" in sys.argv:
        stale.append(area + "/index.js")
    else:
        open(p, "w").write(new)
        print("wrote " + area + "/index.js (%d folders)" % len(ids(area)))
if stale:
    sys.exit("stale (run tools/catalog.py): " + ", ".join(stale))
