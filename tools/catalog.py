#!/usr/bin/env python3
# Writes the feature indexes: island/widgets/index.js and dashboard/widgets/index.js, one line per
# <id>/meta.js folder (R2 C5, the feature-folder contract). A folder with a meta.js is in the shell;
# nothing else has to be edited to add one. tools/check runs this and fails when an index is stale,
# and <area>/tests/index.test.js checks the same thing on `main`, where this script doesn't ship.
#
#   python3 -I tools/catalog.py [--check]        (VTNC = the shell, default the one around tools/)
import os, re, sys

VTNC = os.path.realpath(os.environ.get("VTNC") or os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
# (folder of the index, what it holds, the map's name, folders outside it that also have a meta.js)
AREAS = [
    ("island/widgets", "Iwidget", "WIDGETS", [], "island/widgets/WidgetRegistry.qml", "qs.island.widgets"),
    ("dashboard/widgets", "Dwidget", "WIDGETS", [], "dashboard/widgets/DwidgetRegistry.qml", "qs.dashboard.widgets"),
    # the dashboard and the Settings are apps too, from their own surface folders
    ("apps", "app", "APPS", ["../dashboard", "../settings"], "apps/AppRegistry.qml", "qs.apps"),
]
# a folder outside the area imports as its own module (apps/../settings → qs.settings)
OUTSIDE = {"../dashboard": "qs.dashboard", "../settings": "qs.settings"}
HOT = re.compile(r"^import [\w.]+ // hot reload$", re.M)


def qualifier(wid):
    wid = os.path.basename(wid)
    # "quick" → "Quick", "active-window" → "ActiveWindow"; the qualifier of a `.import`
    return "M" + "".join(p[:1].upper() + p[1:] for p in re.split(r"[-_]", wid))


def ids(area, extra=()):
    """[(id, folder)]: a folder's meta.js describes the one of its own name, or, when it declares
    `var metas`, one per key (the toggle and summary Dwidgets share a folder). `folder` is relative
    to the index, so an entry from outside it reads "../<name>"."""
    d = os.path.join(VTNC, area)
    folders = sorted(n for n in os.listdir(d) if os.path.isfile(os.path.join(d, n, "meta.js")))
    folders += [e for e in extra if os.path.isfile(os.path.join(d, e, "meta.js"))]
    out = []
    for folder in folders:
        src = open(os.path.join(d, folder, "meta.js")).read()
        keys = re.findall(r"^var metas = \{$(.*?)^\};$", src, re.M | re.S)
        if keys:
            out += [(k, folder) for k in re.findall(r"^    (\w+):", keys[0], re.M)]
        else:
            out.append((os.path.basename(folder), folder))
    return out


def index(area, kind, name, extra):
    pairs = ids(area, extra)
    folders = sorted(set(f for _, f in pairs))
    out = [".pragma library\n",
           "\n",
           "// GENERATED by tools/catalog.py: one line per %s folder (<id>/meta.js, or `metas` for a\n" % kind,
           "// folder that holds several). Do not edit; add or remove a folder and run `tools/check`\n",
           "// (or tools/catalog.py). FOLDERS says which folder each id is drawn from.\n"]
    out += ['.import "%s/meta.js" as %s\n' % (f, qualifier(f)) for f in folders]
    out += ["\n", "var %s = {\n" % name]
    out += ["    %s: %s%s\n" % (w, ref(w, f), "," if i < len(pairs) - 1 else "")
            for i, (w, f) in enumerate(pairs)]
    out += ["};\n", "\n", "var FOLDERS = {\n"]
    out += ['    %s: "%s"%s\n' % (w, f, "," if i < len(pairs) - 1 else "")
            for i, (w, f) in enumerate(pairs)]
    out += ["};\n"]
    return "".join(out)


def ref(wid, folder):
    # the folder's own meta, or one of the several a `metas` folder declares
    own = wid == os.path.basename(folder)
    return "%s.meta" % qualifier(folder) if own else "%s.metas.%s" % (qualifier(folder), wid)


def hot_imports(registry, module, folders):
    """The registry's directory imports, one per folder: Quickshell's hot reload only watches a file
    some QML imports, and the widgets are loaded by URL. Rewritten in place, between the first and
    the last `// hot reload` line."""
    p = os.path.join(VTNC, registry)
    src = open(p).read()
    lines = ["import %s // hot reload" % (OUTSIDE[f] if f in OUTSIDE else module + "." + f)
             for f in folders]
    hits = list(HOT.finditer(src))
    if not hits:
        return src, src
    return src, src[:hits[0].start()] + "\n".join(lines) + src[hits[-1].end():]


def launch_apps():
    """base/services/launch.js's VTNC_APPS: the apps whose meta.js declares a launch target. A service
    must not import a feature, so the list is written here instead of read from apps/index.js."""
    rows = []
    for aid, folder in ids("apps", AREAS[2][3]):
        src = open(os.path.join(VTNC, "apps", folder, "meta.js")).read()
        m = re.search(r"launch: \{ title: \"([^\"]+)\", icon: \"([^\"]+)\" \}", src)
        if m:
            rows.append('    %s: { title: "%s", icon: "%s" }' % (aid, m.group(1), m.group(2)))
    return (".pragma library\n\n"
            "// GENERATED by tools/catalog.py from each app's meta.js: the shell apps that have a\n"
            "// launch target (\"vtnc:<id>\"), with the name and icon the pickers show. Do not edit.\n"
            "var APPS = {\n" + ",\n".join(rows) + "\n};\n")


stale = []
def write(path, new, old):
    if old == new:
        return
    if "--check" in sys.argv:
        stale.append(path)
    else:
        open(os.path.join(VTNC, path), "w").write(new)
        print("wrote " + path)


for area, kind, name, extra, registry, module in AREAS:
    # an area whose folders have no meta.js yet (R2 C5 does one area at a time) has no index
    pairs = ids(area, extra)
    if not pairs:
        continue
    p = os.path.join(VTNC, area, "index.js")
    write(area + "/index.js", index(area, kind, name, extra),
          open(p).read() if os.path.exists(p) else None)
    old, new = hot_imports(registry, module, sorted(set(f for _, f in pairs)))
    write(registry, new, old)
p = os.path.join(VTNC, "base/services/launchApps.js")
write("base/services/launchApps.js", launch_apps(), open(p).read() if os.path.exists(p) else None)

if stale:
    sys.exit("stale (run tools/catalog.py): " + ", ".join(stale))
