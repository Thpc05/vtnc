function size(sprite) {
    return { w: sprite[0].length * CELL, h: sprite.length * CELL };
}

// draws `rows` at (x, y) on a 2D context, in its fillStyle (whole pixels: no seams between the rows)
function draw(ctx, rows, x, y) {
    x = Math.round(x);
    y = Math.round(y);
    for (var r = 0; r < rows.length; r++) {
        var row = rows[r];
        var start = -1;
        for (var c = 0; c <= row.length; c++) {
            var on = c < row.length && row.charAt(c) === "#";
            if (on && start < 0)
                start = c;
            else if (!on && start >= 0) {
                ctx.fillRect(x + start * CELL, y + r * CELL, (c - start) * CELL, CELL);
                start = -1;
            }
        }
    }
}
